def t(key: str, lang: str, **fmt) -> str:
    s = I18N.get(key, {}).get(lang) or I18N.get(key, {}).get("en") or key
    if fmt:
        return s.format(**fmt)
    return s


def read_exp_settings(run_dir: Path, arm: str) -> Dict[str, str]:
    """Read env/exp_settings_<arm>.tsv into a dict; missing -> empty."""
    p = run_dir / "env" / f"exp_settings_{arm}.tsv"
    out: Dict[str, str] = {}
    if not p.exists():
        return out
    with p.open() as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("#") or line.startswith("key\tvalue"):
                continue
            if "\t" in line:
                k, _, v = line.partition("\t")
                out[k] = v
    return out


def collect(arm: str, run_dirs: List[Path]) -> Tuple[List[Path], List[Dict[str, float]], List[Dict[str, str]]]:
    summaries: List[Dict[str, float]] = []
    settings: List[Dict[str, str]] = []
    for d in run_dirs:
        summaries.append(bs.read_summary_tsv(d))
        settings.append(read_exp_settings(d, arm))
    return run_dirs, summaries, settings


def fmt_num(v: float) -> str:
    if abs(v) >= 1e9:
        return f"{v:,.0f}"
    if abs(v) >= 1e6:
        return f"{v:,.0f}"
    if abs(v) >= 1000:
        return f"{v:,.0f}"
    return f"{v:.4g}"


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--baseline-arm", required=True)
    p.add_argument("--baseline-runs", nargs="+", required=True)
    p.add_argument("--arm", action="append", required=True)
    p.add_argument("--runs", action="append", nargs="+", required=True)
    p.add_argument("--metrics", nargs="+",
                   default=["minflt_delta", "rss_kb_delta", "rss_kb_pre"])
    p.add_argument("--bootstrap-iters", type=int, default=10000)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--alpha", type=float, default=0.05)
    p.add_argument("--lang", choices=["en", "zh-TW"], default="en")
    p.add_argument("--section-id", default="R-v3")
    p.add_argument("--output", type=Path, required=True)
    args = p.parse_args()

    if len(args.arm) != len(args.runs):
        p.error("--arm and --runs must be paired")

    rng = np.random.RandomState(args.seed)

    # Collect all data
    arms_order = [args.baseline_arm] + args.arm
    arm_data: Dict[str, Tuple[List[Path], List[Dict[str, float]], List[Dict[str, str]]]] = {}
    arm_data[args.baseline_arm] = collect(args.baseline_arm,
                                           [Path(r) for r in args.baseline_runs])
    for arm, runs in zip(args.arm, args.runs):
        arm_data[arm] = collect(arm, [Path(r) for r in runs])

    out: List[str] = []
    out.append(f"# {t('title', args.lang)}")
    out.append("")
    out.append(t("preamble", args.lang))
    out.append("")

    # Dataset summary
    out.append(t("dataset", args.lang))
    out.append("")
    out.append(t("settings_header", args.lang))
    out.append("")
    # Show baseline arm's first rep settings as the canonical recipe
    if arm_data[args.baseline_arm][2]:
        s = arm_data[args.baseline_arm][2][0]
        for k in ("protocol_mode", "bag_flow_s", "bag_burnin_s",
                  "smaps_top_k", "smaps_period_ms", "tier0_sampler",
                  "caret_libcaret_loaded", "caret_record_active",
                  "rmw_implementation"):
            v = s.get(k, "(unknown)")
            out.append(f"- `{k}` = `{v}`")
    out.append("")

    # Per-rep raw numbers
    out.append(t("per_rep", args.lang))
    out.append("")
    cols = [t("col_arm", args.lang), t("col_rep", args.lang), t("col_run_id", args.lang),
            "minflt_delta (count)",
            "rss_kb_delta (KiB)",
            "rss_kb_delta (MiB)",
            "rss_kb_pre (KiB)",
            "rss_kb_pre (MiB)",
            "nprocs (count)",
            "aborts (count)"]
    out.append("| " + " | ".join(cols) + " |")
    out.append("|" + "|".join(["---"] * len(cols)) + "|")
    for arm in arms_order:
        runs, summaries, _ = arm_data[arm]
        for i, (run, summ) in enumerate(zip(runs, summaries), start=1):
            run_id = run.name
            rss_kb_delta = summ.get("rss_kb_delta", 0)
            rss_kb_pre = summ.get("rss_kb_pre", 0)
            row = [arm, str(i), f"`{run_id}`",
                   fmt_num(summ.get("minflt_delta", 0)),
                   fmt_num(rss_kb_delta),
                   f"{rss_kb_delta / 1024:,.1f}",
                   fmt_num(rss_kb_pre),
                   f"{rss_kb_pre / 1024:,.1f}",
                   fmt_num(summ.get("nprocs", 0)),
                   fmt_num(summ.get("aborts", 0))]
            out.append("| " + " | ".join(row) + " |")
    out.append("")

    # Per-metric summary tables
    base_runs, base_summaries, _ = arm_data[args.baseline_arm]
    base_arrays: Dict[str, np.ndarray] = {
        m: np.array([s[m] for s in base_summaries], dtype=np.float64)
        for m in args.metrics
    }

    UNIT_FOR_METRIC = {
        "minflt_delta": "次",
        "rss_kb_delta": "KiB",
        "rss_kb_pre":   "KiB",
    }
    UNIT_LABEL_EN = {
        "minflt_delta": "count",
        "rss_kb_delta": "KiB",
        "rss_kb_pre":   "KiB",
    }
    SHOW_MIB = {"rss_kb_delta", "rss_kb_pre"}

    for metric in args.metrics:
        metric_label = {
            "minflt_delta": t("metric_minflt", args.lang),
            "rss_kb_delta": t("metric_rss_delta", args.lang),
            "rss_kb_pre":   t("metric_rss_pre", args.lang),
        }.get(metric, metric)
        unit = UNIT_FOR_METRIC.get(metric, "") if args.lang == "zh-TW" else UNIT_LABEL_EN.get(metric, "")
        out.append(f"## {metric_label}")
        out.append("")

        cols = [
            t("col_arm", args.lang),
            f"{t('col_mean', args.lang)}（{unit}）" if args.lang == "zh-TW" else f"{t('col_mean', args.lang)} ({unit})",
            t("col_var", args.lang),
            f"{t('col_delta', args.lang)} {args.baseline_arm}（{unit}）" if args.lang == "zh-TW"
            else f"{t('col_delta', args.lang)} {args.baseline_arm} ({unit})",
            t("col_ci", args.lang, iters=args.bootstrap_iters, seed=args.seed),
        ]
        if metric in SHOW_MIB:
            cols.insert(2, "mean (MiB)")
            cols.insert(5, f"Δ (MiB)" if args.lang == "en" else "Δ（MiB）")

        out.append("| " + " | ".join(cols) + " |")
        out.append("|" + "|".join(["---"] * len(cols)) + "|")

        ba = base_arrays[metric]
        ba_mean, ba_sd = float(ba.mean()), float(ba.std(ddof=1)) if len(ba) >= 2 else 0.0
        var_pp = abs(ba.max() - ba.min()) / ba_mean * 100 if ba_mean else 0
        base_row = [args.baseline_arm,
                    f"{fmt_num(ba_mean)} ± {fmt_num(ba_sd)}",
                    f"{var_pp:.2f} %",
                    "(baseline)", "—"]
        if metric in SHOW_MIB:
            base_row.insert(2, f"{ba_mean / 1024:,.1f}")
            base_row.insert(5, "—")
        out.append("| " + " | ".join(base_row) + " |")

        for arm in args.arm:
            _, summaries, _ = arm_data[arm]
            arr = np.array([s[metric] for s in summaries], dtype=np.float64)
            mean_a, sd_a = float(arr.mean()), float(arr.std(ddof=1)) if len(arr) >= 2 else 0.0
            var_a = abs(arr.max() - arr.min()) / mean_a * 100 if mean_a else 0
            delta = mean_a - ba_mean
            delta_pct = delta / ba_mean * 100 if ba_mean else 0
            ci_low, ci_high = bs.bootstrap_paired_diff(ba, arr, args.bootstrap_iters, rng)[1:]
            ci_str = f"[{fmt_num(ci_low)}, {fmt_num(ci_high)}]"
            ci_excl = ci_low * ci_high > 0
            ci_note = " " + t("ci_excludes_zero", args.lang) if ci_excl else ""
            row = [arm,
                   f"{fmt_num(mean_a)} ± {fmt_num(sd_a)}",
                   f"{var_a:.2f} %",
                   f"{fmt_num(delta)} ({delta_pct:+.1f} %)",
                   f"{ci_str}{ci_note}"]
            if metric in SHOW_MIB:
                row.insert(2, f"{mean_a / 1024:,.1f}")
                row.insert(5, f"{delta / 1024:+,.1f}")
            out.append("| " + " | ".join(row) + " |")
        out.append("")

    # Ranking
    out.append(t("ranking_header", args.lang))
    out.append("")
    for metric in args.metrics:
        metric_label = {
            "minflt_delta": t("metric_minflt", args.lang),
            "rss_kb_delta": t("metric_rss_delta", args.lang),
            "rss_kb_pre":   t("metric_rss_pre", args.lang),
        }.get(metric, metric)
        # Compute Δ vs baseline per comparator and order
        pairs = []
        for arm in args.arm:
            _, summaries, _ = arm_data[arm]
            arr_mean = float(np.array([s[metric] for s in summaries], dtype=np.float64).mean())
            ba_mean = float(np.array([s[metric] for s in arm_data[args.baseline_arm][1]], dtype=np.float64).mean())
            pairs.append((arm, arr_mean - ba_mean))
        # For minflt and ΔRSS lower is better (more negative Δ); for rss_pre lower absolute is better but already-mean-is-meaningful
        if metric in ("minflt_delta", "rss_kb_delta"):
            pairs.sort(key=lambda p: p[1])  # most-negative first
        else:
            pairs.sort(key=lambda p: p[1])
        if len(pairs) >= 2:
            top_arm, top_delta = pairs[0]
            second_arm, second_delta = pairs[1]
            gap = abs(top_delta - second_delta)
            rel_gap = second_delta - top_delta
            sign = "+" if rel_gap >= 0 else ""
            out.append(f"- **{metric_label}**: {top_arm} {t('wins', args.lang, metric=metric_label, gap=fmt_num(gap))} → {second_arm} {sign}{fmt_num(rel_gap)} (relative)")
    out.append("")

    out.append(t("audit_chain", args.lang))
    out.append("")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(out))
    sys.stderr.write(f"wrote {args.output}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
