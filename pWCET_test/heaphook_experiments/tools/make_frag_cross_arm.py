#!/usr/bin/env python3
"""Aggregate per-rep frag_summary.tsv into cross-arm frag comparison.

Usage:
    tools/make_frag_cross_arm.py \\
        --arm A --runs runs/A1 runs/A2 \\
        --arm B --runs runs/B1 runs/B2 \\
        --arm D-v4 --runs runs/D1 runs/D2 \\
        --output reports/cross_abcd_v4_frag_zh-TW.md \\
        --lang zh-TW

Reads each rep's `derived/frag_summary.tsv` (produced by
`tools/post_process_frag.py`), extracts the per-arm aggregate footer
(`# arm=<X>  mean_frag_ratio=<X>  stddev_frag_ratio=<X>  ...`),
and renders a Markdown report with:

  - per-rep raw aggregate row (one per arm × rep)
  - per-arm summary (mean ± SD across reps)
  - cross-arm Δ vs baseline (default A) — direct subtraction (no
    bootstrap; frag_ratio is already a within-rep aggregate).

Languages: en (default), zh-TW.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Dict, List, Tuple

I18N: Dict[str, Dict[str, str]] = {
    "title": {
        "en":    "Cross-arm fragmentation comparison — auto-generated",
        "zh-TW": "跨 arm fragmentation 比較表 — 自動產生",
    },
    "preamble": {
        "en":    "Auto-generated by `tools/make_frag_cross_arm.py` from each rep's `derived/frag_summary.tsv`. The TSV is produced by `tools/post_process_frag.py` from per-PID `heaphook_frag_<pid>.tsv` files emitted by `libheaphook_sampler.so`.",
        "zh-TW": "由 `tools/make_frag_cross_arm.py` 從各 rep 的 `derived/frag_summary.tsv` 自動產生。該 TSV 由 `tools/post_process_frag.py` 從 `libheaphook_sampler.so` 產出的 per-PID `heaphook_frag_<pid>.tsv` 整合而來。",
    },
    "metric_def": {
        "en":    "Metric definition: `frag_ratio = 1 − largest_free / (capacity − allocated)`. Range [0, 1]; lower = less fragmented; higher = more fragmented.",
        "zh-TW": "指標定義：`frag_ratio = 1 − largest_free / (capacity − allocated)`。範圍 [0, 1]；越低 = 碎片越少；越高 = 碎片越嚴重。",
    },
    "per_rep": {"en": "## Per-rep raw numbers (per-arm aggregate footer)", "zh-TW": "## 每 rep 原始數字（per-arm 聚合 footer）"},
    "per_arm": {"en": "## Per-arm summary (mean ± SD across reps)",         "zh-TW": "## 每 arm 摘要（rep 間 mean ± SD）"},
    "ranking": {"en": "## Cross-arm ranking (Δ vs baseline)",                "zh-TW": "## 跨 arm 排名（Δ vs 基準）"},
    "audit_chain": {
        "en":    "## Audit chain\n\nEach run's `derived/frag_summary.tsv` lists the 381+ per-PID rows + the `# arm=X` aggregate footer used here. Per-PID `raw/<arm>/frag/heaphook_frag_<pid>.tsv` files are the immutable source.",
        "zh-TW": "## 證據鏈\n\n每 run 的 `derived/frag_summary.tsv` 含 ~381 per-PID rows 以及本表使用的 `# arm=X` 聚合 footer。Per-PID 原始檔在 `raw/<arm>/frag/heaphook_frag_<pid>.tsv` 為不變來源。",
    },
}


def t(key: str, lang: str) -> str:
    return I18N.get(key, {}).get(lang, I18N.get(key, {}).get("en", key))


_ARM_FOOTER_RE = re.compile(
    r"^#\s*arm=(?P<arm>\S+)\s+n_pids=(?P<n_pids>\d+)\s+"
    r"total_peak_allocated=(?P<peak>\d+)\s+"
    r"mean_frag_ratio=(?P<mean>[-\d.]+)\s+"
    r"stddev_frag_ratio=(?P<sd>[-\d.]+)\s*$"
)


def read_frag_summary(run_dir: Path) -> Dict[str, Dict[str, float]]:
    """Return arm → {n_pids, total_peak_allocated, mean_frag_ratio, stddev}."""
    p = run_dir / "derived" / "frag_summary.tsv"
    if not p.exists():
        return {}
    out: Dict[str, Dict[str, float]] = {}
    with p.open() as f:
        for line in f:
            m = _ARM_FOOTER_RE.match(line.strip())
            if m:
                out[m.group("arm")] = {
                    "n_pids": float(m.group("n_pids")),
                    "total_peak_allocated": float(m.group("peak")),
                    "mean_frag_ratio": float(m.group("mean")),
                    "stddev_frag_ratio": float(m.group("sd")),
                }
    return out


def mean_sd(xs: List[float]) -> Tuple[float, float]:
    if not xs:
        return (0.0, 0.0)
    n = len(xs)
    mu = sum(xs) / n
    if n < 2:
        return (mu, 0.0)
    var = sum((x - mu) ** 2 for x in xs) / (n - 1)
    return (mu, var ** 0.5)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--baseline-arm", default="A")
    p.add_argument("--arm", action="append", required=True)
    p.add_argument("--runs", action="append", nargs="+", required=True)
    p.add_argument("--lang", choices=["en", "zh-TW"], default="zh-TW")
    p.add_argument("--output", required=True, type=Path)
    args = p.parse_args()

    if len(args.arm) != len(args.runs):
        p.error("--arm and --runs must be paired")

    # The arm key inside frag_summary.tsv may be A/B/D (single-letter) — we
    # need to map our --arm labels to those single-letter keys.
    # Strategy: for each provided run dir, read the frag summary; the
    # SAMPLE keys returned are the single-letter ones — we use whichever
    # key has the largest n_pids (in case multiple are present in hybrid
    # mode, A/D may both appear; keep the one matching --arm slot).
    label_to_key = {"A": "A", "B": "A",  # B reps emit `A` rows from glibc provider (mallinfo2)
                     "D-v4": "D"}

    arm_data: Dict[str, List[Dict[str, float]]] = {}
    for label, run_list in zip(args.arm, args.runs):
        rows: List[Dict[str, float]] = []
        for r in run_list:
            d = read_frag_summary(Path(r))
            # Pick the row matching the label's expected single-letter key,
            # with fallback: the row with the most n_pids.
            expected = label_to_key.get(label, label[:1])
            chosen = d.get(expected)
            if chosen is None and d:
                chosen = max(d.values(), key=lambda v: v.get("n_pids", 0))
            if chosen:
                rows.append({"run": Path(r).name, **chosen})
        arm_data[label] = rows

    out_lines: List[str] = []
    out_lines.append(f"# {t('title', args.lang)}")
    out_lines.append("")
    out_lines.append(t("preamble", args.lang))
    out_lines.append("")
    out_lines.append(t("metric_def", args.lang))
    out_lines.append("")

    # Per-rep raw
    out_lines.append(t("per_rep", args.lang))
    out_lines.append("")
    out_lines.append("| arm | run_id | n_pids | mean_frag_ratio | stddev | n_pids 是什麼 |"
                     if args.lang == "zh-TW"
                     else "| arm | run_id | n_pids | mean_frag_ratio | stddev | meaning |")
    out_lines.append("|---|---|---|---|---|---|")
    for label, rows in arm_data.items():
        for r in rows:
            out_lines.append(
                f"| {label} | `{r['run']}` | {int(r['n_pids'])} | "
                f"{r['mean_frag_ratio']:.4f} | {r['stddev_frag_ratio']:.4f} | "
                "全 rep 內所有 PID 樣本聚合 |"
                if args.lang == "zh-TW"
                else f"| {label} | `{r['run']}` | {int(r['n_pids'])} | "
                     f"{r['mean_frag_ratio']:.4f} | {r['stddev_frag_ratio']:.4f} | "
                     "all-PID samples aggregate |"
            )
    out_lines.append("")

    # Per-arm summary
    out_lines.append(t("per_arm", args.lang))
    out_lines.append("")
    out_lines.append("| arm | rep 間 mean_frag_ratio (mean ± SD) | rep 間 mean (across reps) | n_reps | n_pids 平均 |"
                     if args.lang == "zh-TW"
                     else "| arm | mean_frag_ratio across reps (mean ± SD) | reps | avg n_pids |")
    out_lines.append("|---|---|---|---|" + ("---|" if args.lang == "zh-TW" else ""))
    arm_summary: Dict[str, Tuple[float, float, int, float]] = {}
    for label, rows in arm_data.items():
        ratios = [r["mean_frag_ratio"] for r in rows]
        n_pids = [r["n_pids"] for r in rows]
        mu, sd = mean_sd(ratios)
        arm_summary[label] = (mu, sd, len(ratios), sum(n_pids) / max(len(n_pids), 1))
        if args.lang == "zh-TW":
            out_lines.append(
                f"| {label} | {mu:.4f} ± {sd:.4f} | {mu:.4f} | {len(ratios)} | "
                f"{arm_summary[label][3]:.0f} |"
            )
        else:
            out_lines.append(
                f"| {label} | {mu:.4f} ± {sd:.4f} | {len(ratios)} | "
                f"{arm_summary[label][3]:.0f} |"
            )
    out_lines.append("")

    # Ranking
    out_lines.append(t("ranking", args.lang))
    out_lines.append("")
    base_mu = arm_summary.get(args.baseline_arm, (0.0,))[0]
    if args.lang == "zh-TW":
        out_lines.append(
            f"基準 arm = **{args.baseline_arm}**（mean_frag_ratio = {base_mu:.4f}）"
        )
        out_lines.append("")
        out_lines.append("| arm | mean | Δ vs 基準（絕對）| Δ vs 基準（相對 %）| 解讀 |")
    else:
        out_lines.append(
            f"Baseline arm = **{args.baseline_arm}** (mean_frag_ratio = {base_mu:.4f})"
        )
        out_lines.append("")
        out_lines.append("| arm | mean | Δ vs baseline (abs) | Δ vs baseline (%) | reading |")
    out_lines.append("|---|---|---|---|---|")
    for label, (mu, sd, n, _) in arm_summary.items():
        if label == args.baseline_arm:
            interp = ("（基準）" if args.lang == "zh-TW" else "(baseline)")
            out_lines.append(f"| {label} | {mu:.4f} | — | — | {interp} |")
        else:
            d = mu - base_mu
            d_pct = (d / base_mu * 100) if base_mu else 0.0
            if args.lang == "zh-TW":
                interp = ("更碎片化（高 = 內部空間零碎）" if d > 0
                          else "比基準乾淨（低 = 連續可用空間多）")
            else:
                interp = ("more fragmented (high = scattered free)" if d > 0
                          else "cleaner than baseline (low = larger contiguous free)")
            out_lines.append(
                f"| {label} | {mu:.4f} | {d:+.4f} | {d_pct:+.1f} % | {interp} |"
            )
    out_lines.append("")

    out_lines.append(t("audit_chain", args.lang))
    out_lines.append("")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(out_lines))
    sys.stderr.write(f"wrote {args.output}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
